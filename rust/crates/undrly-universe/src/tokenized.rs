//! Tokenized stocks (V1.10, docs/v1.10-tokenized-stocks.md): each issuer's
//! own product registry → one `tokenized_security` per product, its edge to
//! the share it is tied to, and its deployments.
//!
//! | Issuer | Registry | Product identity | Edge to the share |
//! | --- | --- | --- | --- |
//! | Backed Assets (JE) Limited (xStocks) | `backed-api` | its own ISIN | `TRACKS` (tracker certificates) |
//! | Backpack Securities | `backpack` | its Solana mint | `TOKENIZES` (claim on an SPV holding the share, redeemable 1:1) |
//! | Robinhood Assets (Jersey) Limited | `rhj-api` | its registry uid | `TRACKS` (tracker certificates, V1.6) |
//!
//! The share is found **by identifier only**: a US ISIN's NSIN is its CUSIP
//! (ISO 6166; the US numbering agency is CUSIP Global Services), so an
//! ISIN `US<CUSIP><check>` names the imported equity keyed by that CUSIP;
//! Backpack states the CUSIP itself. The registry's ticker must then agree
//! with the equity's listing symbol: a disagreement rejects the match (it is
//! a check, never a way to find one). A product whose share is not an
//! imported equity is excluded and reported.
//!
//! The same matches give imported equities their ISIN, as the issuers state
//! it (never constructed from a CUSIP).
//!
//! Deployments are written to their own file (`deployments.json`): chains are
//! ingested by `undrly-collect onchain` from the chains themselves, so
//! deployments are ingested there, after them. Solana deployments are priced
//! by Jupiter, keyed by mint; their bars come from their deepest
//! GeckoTerminal pool (§13), declared here as that DEX's market.

